import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { runCase } from './run-case.js';

interface ParityCase {
  id: string;
  tool: string;
  input: Record<string, unknown>;
  expected: Record<string, unknown>;
  explanation: string;
  citations: string[];
}

const fixture = JSON.parse(
  readFileSync(fileURLToPath(new URL('./fixtures/parity.json', import.meta.url)), 'utf8'),
) as { cases: ParityCase[] };

/**
 * The claim this suite exists to defend: the same inputs produce the same numbers
 * in PHP and in TypeScript, down to the paisa and down to the wording of the
 * working.
 *
 * The fixture is generated by running crmleaf/payroll-core itself - see
 * scripts/generate-parity-fixture.php - so a failure here means one engine has
 * moved and the other has not. Fix the code or regenerate the fixture; never edit
 * it by hand.
 */
describe('parity with crmleaf/payroll-core', () => {
  it('covers every backend-free tool', () => {
    const covered = new Set(fixture.cases.map((entry) => entry.tool));

    expect([...covered].sort()).toEqual([
      'bonus',
      'complianceCalendar',
      'ctc',
      'epfoPenalty',
      'esi',
      'fnf',
      'gratuity',
      'incomeTax',
      'leaveEncashment',
      'pf',
      'roi',
      'savings',
      'tds',
    ]);
  });

  for (const entry of fixture.cases) {
    describe(`${entry.tool}: ${entry.id}`, () => {
      const result = runCase(entry.tool, entry.input);

      it('produces the same figures', () => {
        expect(JSON.parse(JSON.stringify(result.toArray()))).toEqual(entry.expected);
      });

      it('explains itself the same way', () => {
        expect(result.explain()).toBe(entry.explanation);
      });

      it('cites the same authorities', () => {
        expect([...result.citations]).toEqual(entry.citations);
      });
    });
  }
});
